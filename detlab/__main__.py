"""CLI.

  python -m detlab hunt data/intrusion-day.jsonl     # run all rules over a log file
  python -m detlab coverage                          # write docs/coverage.md (ATT&CK matrix)
"""
import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

from .engine import load_events, load_rules, run

ROOT = Path(__file__).resolve().parents[1]
TACTICS = {
    "T1059": "Execution", "T1204": "Execution", "T1027": "Defense Evasion", "T1070": "Defense Evasion",
    "T1562": "Defense Evasion", "T1003": "Credential Access", "T1110": "Credential Access",
    "T1566": "Initial Access", "T1053": "Persistence", "T1490": "Impact", "T1105": "Command and Control",
}


def hunt(path: str) -> int:
    alerts = run(load_rules(ROOT / "rules"), load_events(path))
    for a in alerts:
        print(json.dumps({"rule": a.rule_id, "level": a.level, "title": a.title,
                          "attack": a.attack, "first_event": a.events[0]["UtcTime"], "events": len(a.events)}))
    print(f"# {len(alerts)} alerts", file=sys.stderr)
    return 1 if any(a.level == "critical" for a in alerts) else 0


def coverage() -> str:
    by_tactic = defaultdict(list)
    for rule in load_rules(ROOT / "rules"):
        for t in rule.spec["attack"]:
            by_tactic[TACTICS.get(t.split(".")[0], "Other")].append((t, rule.id, rule.spec["title"]))
    lines = ["# ATT&CK coverage", "", "Generated by `python -m detlab coverage`. Do not edit by hand.", "",
             "| Tactic | Technique | Rule | Title |", "|---|---|---|---|"]
    for tactic in sorted(by_tactic):
        for t, rid, title in sorted(by_tactic[tactic]):
            lines.append(f"| {tactic} | [{t}](https://attack.mitre.org/techniques/{t.replace('.', '/')}/) | {rid} | {title} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="detlab")
    sub = ap.add_subparsers(dest="cmd", required=True)
    h = sub.add_parser("hunt")
    h.add_argument("logfile")
    sub.add_parser("coverage")
    args = ap.parse_args(argv)
    if args.cmd == "hunt":
        return hunt(args.logfile)
    out = ROOT / "docs" / "coverage.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(coverage(), encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
